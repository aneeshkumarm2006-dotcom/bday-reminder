/**
 * Country dial codes (E.164 country calling codes) and the IANA-zone hints used
 * to preselect one.
 *
 * Auto-send texts go out through Twilio, which is now provisioned beyond the
 * US/CA — so a number typed without a country code can no longer be assumed to
 * be +1. Every phone field in the app and on the site pairs a country picker
 * with the national number and stores the combined E.164 string, which is the
 * only format Twilio (and the `sms:` greeting shortcut) accept reliably.
 *
 * Mirrored across backend / app / website - same as `lib/phone.ts`. Keep the
 * three copies in step.
 */

export interface Country {
  /** ISO 3166-1 alpha-2, e.g. "IN". Also the picker's option value. */
  code: string;
  name: string;
  /** E.164 country calling code WITHOUT the leading "+", e.g. "91". */
  dial: string;
  /**
   * True for the country a shared dial code resolves back to when parsing a
   * stored number (e.g. "+1" -> US, not Canada; "+7" -> Russia, not Kazakhstan).
   * Only the dial code is ever sent, so the choice is cosmetic.
   */
  primary?: boolean;
}

