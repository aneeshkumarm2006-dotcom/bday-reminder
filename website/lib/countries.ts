const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

/** Dial codes longest-first, so parsing matches "+1868" before "+1". */
const DIALS_BY_LENGTH = [...COUNTRIES].sort((a, b) => b.dial.length - a.dial.length);

/** Look up a country by ISO 3166-1 alpha-2 code. */
export function countryByCode(code: string | null | undefined): Country | undefined {
  return code ? BY_CODE.get(code.toUpperCase()) : undefined;
}

/** Dial code for an ISO code, e.g. "IN" -> "91". Falls back to the US ("1"). */
export function dialCodeFor(code: string | null | undefined): string {
  return countryByCode(code)?.dial ?? "1";
}

/**
 * The country a stored E.164 number belongs to, by longest-matching dial code.
 * Shared codes resolve to the `primary` country (see {@link Country.primary}).
 */
export function countryForE164(value: string | null | undefined): Country | undefined {
  if (!value) return undefined;
  const digits = value.trim().replace(/[^\d+]/g, "");
  if (!digits.startsWith("+")) return undefined;
  const national = digits.slice(1);
  for (const c of DIALS_BY_LENGTH) {
    if (!national.startsWith(c.dial)) continue;
    return COUNTRIES.find((o) => o.dial === c.dial && o.primary) ?? c;
  }
  return undefined;
}

/**
 * ISO code guessed from an IANA timezone, so a phone field opens on the user's
 * own country instead of always on the US. Unknown zones return undefined and
 * the caller keeps its own default.
 */
export function countryCodeForTimeZone(zone: string | null | undefined): string | undefined {
  return zone ? COUNTRY_BY_TIMEZONE[zone] : undefined;
}

